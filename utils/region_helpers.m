function varargout = region_helpers(action,varargin)
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%REGION_HELPERS Centralized region metadata and lookup utility for SAGE.
%
% SYNOPSIS:
%   out = region_helpers(action,...)
%   [latLim,lonLim,mapName] = region_helpers('maplimits',region,lat,lon)
%
% INPUT:
%   action   Character/string specifying the requested region operation:
%              'code'            canonical CAMELS region code
%              'short'           short region tag
%              'name'            display name
%              'regiondir'       region-module directory path
%              'basindir'        compatibility alias for regiondir
%              'basinfile'       region-prefixed basin/split filename
%              'maplimits'       registered map limits; optional basin
%                                coordinates are used as a generic fallback
%              'capital'         capital city latitude, longitude, and name
%              'variogramrange'  default variogram fitting range
%              'variogramtick'   default variogram tick spacing
%              'naturalearth'    Natural Earth country name
%              'config'          load regions/XX/region_config_XX.m
%              'resolutions'     supported resolutions from the config
%              'resolution'      selected resolution-specific config
%              'resolvepaths'    resolve dirD/dirM/dirQ from a config
%              'list'            display names and canonical codes
%
%   varargin Additional inputs required by the selected action
%
% OUTPUT:
%   varargout Output requested by action
%
% DESCRIPTION:
%   This helper provides a single registry-based interface for region
%   metadata used throughout SAGE-GUI. It maps aliases, folder names,
%   structures with region or dirD fields, and canonical CAMELS identifiers
%   to a consistent regional definition. The registry controls short tags,
%   display names, map limits, Natural Earth names, basin filename prefixes
%   and variogram plotting defaults.
%
% NOTES:
%   New regions should be added only in region_registry using 1 additional
%   reg(...) entry. The remaining helper functions use the registry and do
%   not require region-specific edits.
%
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% © Written by Jasper A. Vrugt, June 2026                                 %
% University of California, Irvine                                        %
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

    switch lower(action)
    
        case 'code'
            varargout{1} = ...
                region_code(varargin{:});
    
        case 'short'
            varargout{1} = ...
                region_short(varargin{:});
    
        case 'name'
            varargout{1} = ...
                region_name(varargin{:});
    
        case {'regiondir','basindir'}
            varargout{1} = ...
                fullfile(varargin{1}, ...
                'regions',region_short(varargin{2}));
    
        case 'basinfile'
            varargout{1} = ...
                region_basin_file(varargin{:});
    
        case 'maplimits'
            [varargout{1:nargout}] = ...
                region_map_limits(varargin{:});
    
        case 'capital'
            [varargout{1:nargout}] = ...
                region_capital(varargin{:});
            
        case 'variogramrange'
            varargout{1} = ...
                region_variogram_range(varargin{:});
    
        case 'variogramtick'
            varargout{1} = ...
                region_variogram_tick_step(varargin{:});
    
        case {'naturalearth','country','country_name'}
            varargout{1} = region_naturalearth_name(varargin{:});

        case 'config'
            varargout{1} = region_config_load(varargin{:});

        case 'resolutions'
            C = region_config_load(varargin{:});
            varargout{1} = C.resolutions;

        case {'resolution','resolutionconfig'}
            C = region_config_load(varargin{1},varargin{2});
            varargout{1} = region_resolution_config(C,varargin{3});

        case {'resolvepaths','paths'}
            varargout{1} = region_resolve_paths(varargin{:});

        case {'list','regions'}
            R = region_registry();
            varargout{1} = {R.name};
            if nargout > 1
                varargout{2} = {R.code};
            end

        otherwise
            varargout{1} = 'CAMELS_US';
    end
end

