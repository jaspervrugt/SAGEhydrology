    if ~strcmpi(char(string(C.code)),expected)
        error('region_helpers:RegionConfigMismatch', ...
            ['Configuration %s declares ' ...
            '%s, but %s was requested.'], ...
            cfgFile,char(string(C.code)),expected);
    end
end

function X = region_resolution_config(C,resolution)
%REGION_RESOLUTION_CONFIG Return one resolution-specific block.

    requested = char(string(resolution));
    key = strrep(requested,' ','_');
    if strcmpi(key,'15_minutes')
        key = 'min15';
    end

    fields = fieldnames(C.by_resolution);
    idx = find(strcmpi(fields,key),1);

    if isempty(idx)
        error('region_helpers:UnsupportedResolution', ...
            '%s does not support resolution "%s".', ...
            C.code,requested);
    end

    X = C.by_resolution.(fields{idx});
end


function P = region_resolve_paths(C,X,dataRoot)
%REGION_RESOLVE_PATHS Resolve generic regional runtime directories.
%
% All X.paths entries are relative to Data/<C.data_root>.

    if nargin < 3
        error('region_helpers:PathInputs', ...
            ['Provide region config, ' ...
            'resolution config, and data root.']);
    end
    if ~isstruct(C) ...
            || ~isfield(C,'data_root')
        error('region_helpers:InvalidPathConfig', ...
            'The region configuration lacks data_root.');
    end
    if ~isstruct(X) ...
            || ~isfield(X,'paths')
        error('region_helpers:InvalidResolutionPaths', ...
            'The resolution configuration lacks paths.');
    end

    regionRoot = fullfile(char(string(dataRoot)), ...
        char(string(C.data_root)));

    runRoot = '';
    if isfield(X.paths,'run_root')
        runRoot = char(string(X.paths.run_root));
    elseif isfield(X.paths,'region_subdir')
        % Transitional compatibility with older configuration files.
        runRoot = char(string(X.paths.region_subdir));
    end

    P = struct();
    P.data_root = char(string(dataRoot));
    P.region_root = regionRoot;
    P.dirD = local_join_relative(regionRoot, ...
        runRoot);
    P.dirM = local_join_relative(regionRoot, ...
        X.paths.meteo);
    P.dirQ = local_join_relative(regionRoot, ...
        X.paths.discharge);
    P.dt = double(X.dt);
end

function out = local_join_relative(base,relativePath)
    rel = char(string(relativePath));
    if isempty(strtrim(rel))
        out = base;
    else
        out = fullfile(base,rel);
    end
end

function tf = local_path_contains(folder)
    entries = strsplit(path,pathsep);
    tf = any(strcmpi(string(entries),string(folder)));
end

function local_remove_path(folder)
    try
        if local_path_contains(folder)
            rmpath(folder);
        end
    catch
    end
end

function fname = region_basin_file(region,fname)

    fname = char(strtrim(string(fname)));
    
    if isempty(fname) ...
            || isfile(fname) ...
            || contains(fname,filesep)
        return
    end
    
    [pth,nam,ext] = fileparts(fname);
    if ~isempty(pth)
        return
    end
    
    r = region_short(region);
    
    R = region_registry();
    shorts = string({R.short});
    [~,ix] = sort(strlength(shorts),'descend');
    shorts = shorts(ix);
    pat = ['(' char(strjoin(shorts + "_","|")) ')'];
    
    if startsWith(nam,'split_')
        nam = regexprep(nam, ...
            ['^split_' pat '?'], '');
        fname = ['split_' r '_' nam ext];
    else
        nam = regexprep(nam, ...
            ['^' pat], '');
        fname = [r '_' nam ext];
    end

end
