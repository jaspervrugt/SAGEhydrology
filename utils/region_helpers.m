        otherwise
            error('region_helpers:UnknownRegionConfig', ...
                ['No regional configuration ' ...
                'is registered for %s.'],short);
    end

    if ~isstruct(C) || ~isfield(C,'code') ...
            || ~isfield(C,'resolutions') ...
            || ~isfield(C,'by_resolution')
        error('region_helpers:InvalidRegionConfig', ...
            ['%s did not return the expected ' ...
            'configuration structure.'], ...
