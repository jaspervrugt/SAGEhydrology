            C = region_config_CL();
        case 'COL'
            C = region_config_COL();
        case 'CZ'
            C = region_config_CZ();
        case 'DE'
            C = region_config_DE();
        case 'DK'
            C = region_config_DK();
        case 'ES'
            C = region_config_ES();
        case 'EE'
            C = region_config_EE();
        case 'FI'
            C = region_config_FI();
        case 'FR'
            C = region_config_FR();
        case 'GB'
            C = region_config_GB();
