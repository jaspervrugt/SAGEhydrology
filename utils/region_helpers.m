function R = region_lookup(v)

    if nargin == 0 ...
            || isempty(v)
        v = 'CAMELS_FR';
    end
    
    if isstruct(v)
        if isfield(v,'region') ...
                && ~isempty(v.region)
            v = v.region;
        elseif isfield(v,'dirD') ...
                && ~isempty(v.dirD)
            v = v.dirD;
        else
            v = 'CAMELS_FR';
        end
    end

    Rall = region_registry();
    s = upper(strtrim(string(v)));
    s = replace(s,'-','_');
    sChar = char(s);
    for k = 1:numel(Rall)
        if contains(sChar,Rall(k).code)
            R = Rall(k);
            return
        end
    end
    for k = 1:numel(Rall)
        if any(s == Rall(k).aliases) ...
                || s == Rall(k).code
            R = Rall(k);
            return
        end
    end
    idx = strcmp({Rall.code},'CAMELS_US');
    R = Rall(idx);

end

