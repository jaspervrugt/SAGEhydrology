function [latLim,lonLim,mapName] = region_map_limits(region,lat,lon)

    R = region_lookup(region);
    latLim = double(R.latLim);
    lonLim = double(R.lonLim);
    mapName = char(R.mapName);

    % The registry is the single source of region-specific map limits.
    % Coordinates are only a generic fallback when a newly added registry
    % entry accidentally contains missing or invalid limits.
    if local_valid_limits(latLim,lonLim)
        return
    end

    latLim = [];
    lonLim = [];
    if nargin >= 3 ...
            && ~isempty(lat) ...
            && ~isempty(lon)
        coords = [lat(:),lon(:)];
        [latLim,lonLim] = localCoordinateMapLimits(coords);
    end

    if ~local_valid_limits(latLim,lonLim)
        error('region_helpers:InvalidMapLimits', ...
            ['Region %s has invalid map limits. ' ...
            'Update its single reg(...) ' ...
             'entry in region_registry.'],R.code);
    end
end

function [latLim,lonLim] = localCoordinateMapLimits(coords)
    latLim = [];
    lonLim = [];
    if isempty(coords) ...
            || ~isnumeric(coords) ...
            || size(coords,2) < 2
        return
    end
    lat = double(coords(:,1));
    lon = double(coords(:,2));
    good = isfinite(lat) ...
        & isfinite(lon) ...
        & lat >= -90 ...
        & lat <= 90 ...
        & lon >= -180 ...
        & lon <= 180;
    lat = lat(good);
    lon = lon(good);
    if isempty(lat)
        return
    end
    dlat = max(0.5,0.10*max(max(lat)-min(lat),1));
    dlon = max(0.5,0.10*max(max(lon)-min(lon),1));
    latLim = [max(-90,min(lat)-dlat), min(90,max(lat)+dlat)];
    lonLim = [max(-180,min(lon)-dlon), min(180,max(lon)+dlon)];
end

function tf = local_valid_limits(latLim,lonLim)
    tf = isnumeric(latLim) ...
        && isnumeric(lonLim) ...
        && numel(latLim) == 2 ...
        && numel(lonLim) == 2 ...
        && all(isfinite(latLim)) ...
        && all(isfinite(lonLim)) ...
        && latLim(1) < latLim(2) ...
        && lonLim(1) < lonLim(2);
end


function C = region_config_load(SAGEhydro,region)
%REGION_CONFIG_LOAD Load regions/XX/region_config_XX.m.

    if nargin < 2
        error('region_helpers:ConfigInputs', ...
            'Provide the SAGEhydrology directory and region.');
    end

    sageDir = char(string(SAGEhydro));
    short = region_short(region);
    cfgDir = fullfile(sageDir,'regions',short);
    cfgFile = fullfile(cfgDir,['region_config_' short '.m']);

    % In normal MATLAB, verify the source file and temporarily add its
    % region folder to the path. In a deployed application, the config
    % functions are compiled into the CTF and do not need to exist as
    % loose .m files beside the executable.
    if ~isdeployed
        if ~isfile(cfgFile)
            error('region_helpers:MissingRegionConfig', ...
                'Regional configuration file not found: %s',cfgFile);
        end

        wasOnPath = local_path_contains(cfgDir);
        if ~wasOnPath
            addpath(cfgDir);
            cleanupPath = onCleanup(@()local_remove_path(cfgDir));
        end
    end

    % Explicit dispatch keeps MATLAB Compiler dependencies visible.
    switch short
        case 'AT'
            C = region_config_AT();
        case 'AR'
            C = region_config_AR();
        case 'BE'
            C = region_config_BE();
        case 'AU'
