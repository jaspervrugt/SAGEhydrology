function [country,count] = local_grdc_region(region)

    switch region
        case 'CAMELS_AR'
            country = 'Argentine';
            count = 59;
        case 'CAMELS_BE'
            country = 'Belgian';
            count = 55;
        case 'CAMELS_EE'
            country = 'Estonian';
            count = 51;
        case 'CAMELS_IE'
            country = 'Irish';
            count = 43;
        case 'CAMELS_JM'
            country = 'Jamaican';
            count = 12;
        case 'CAMELS_NA'
            country = 'Namibian';
            count = 51;
        case 'CAMELS_NO'
            country = 'Norwegian';
            count = 206;
        case 'CAMELS_PR'
            country = 'Puerto Rican';
            count = 24;
        case 'CAMELS_ZA'
            country = 'South African';
            count = 434;
        otherwise
            country = 'regional';
            count = 0;
    end
end
