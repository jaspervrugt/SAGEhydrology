"""Generate artificial basins and run the public SAGE training backend."""

import argparse
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from run_sage import execute
import numpy as np
import pandas as pd
from sage_schema import session_defaults
from regional_data import read_region
from crr_native import simulate


def configuration(folder):
    """Create deterministic CAMELS-shaped artificial inputs and settings.

    All observations are generated by HYMOD. The files are artificial
    fixtures, not observations from real catchments or a provider dataset.
    """
    root = Path(folder).resolve()
    root.mkdir(parents=True, exist_ok=False)
    gauges = [f"{i:08d}" for i in range(1, 5)]
    dates = pd.date_range("2005-09-26", periods=65)
    rows = pd.DataFrame(
        dict(
            gauge_id=gauges,
            gauge_name=["Artificial " + g for g in gauges],
            gauge_lat=[40, 41, 42, 43],
            gauge_lon=[-100, -101, -102, -103],
            elev_mean=[100, 200, 300, 400],
            area_gages2=[100, 100, 100, 100],
            p_mean=[2, 3, 4, 5],
            pet_mean=[1, 1, 1, 1],
            frac_snow=[0.1, 0.1, 0.1, 0.1],
            aridity=[0.5, 0.6, 0.7, 0.8],
        )
    )
    for name in (
        "clim",
        "geol",
        "hydro",
        "soil",
        "topo",
        "vege",
        "name_clean",
    ):
        rows.to_csv(
            root / ("camels_" + name + ".txt"), sep=";", index=False
        )
    forcing = root / "daily/v1p2/forcing/daymet/01"
    flow = root / "daily/v1p2/streamflow/01"
    forcing.mkdir(parents=True)
    flow.mkdir(parents=True)
    config = session_defaults()
    config.update(
        data_root=str(root),
        gauges=gauges,
        product="daymet",
        attributes=["p_mean", "elev_mean", "aridity"],
        train_start="2005-10-01",
        train_end="2005-11-09",
        eval_start="2005-11-10",
        eval_end="2005-11-29",
        spinup=5,
        hidden_widths=[3],
        activations=["tanh"],
        max_iter=3,
        basin_train_fraction=0.75,
        parallel=False,
        workers=2,
        max_pending=2,
        diagnostics=dict(attribution=False),
    )
    parameters = config["model_parameters"]["1"]["parameters"]
    config.update(
        lower=[p["lower"] for p in parameters],
        upper=[p["upper"] for p in parameters],
    )
    for i, gauge in enumerate(gauges):
        precipitation = (1 + i * 0.2) * (0.5 + 7 * (np.arange(65) % 6 == 0))
        lines = [
            "40",
            "100",
            "100000000",
            (
                "Year Mnth Day Hr dayl(s) prcp(mm/day) srad(W/m2) "
                "swe(mm) tmax(C) tmin(C) vp(Pa)"
            ),
        ]
        lines += [
            f"{d.year} {d.month} {d.day} 0 40000 {p} 100 0 15 5 800"
            for d, p in zip(dates, precipitation)
        ]
        (forcing / (gauge + "_lump_cida_forcing_leap.txt")).write_text(
            "\n".join(lines) + "\n", encoding="utf-8"
        )
        destination = flow / (gauge + "_streamflow_qc.txt")
        destination.write_text(
            "".join(
                f"{gauge} {d.year} {d.month} {d.day} 1 A\n" for d in dates
            ),
            encoding="utf-8",
        )
        data = read_region(
            root,
            gauge,
            region="CAMELS_US",
            sage_root=config["sage_root"],
            product="daymet",
            pet=config["pet"],
            spinup=config["spinup"],
            train_start=config["train_start"],
            train_end=config["train_end"],
            eval_start=config["eval_start"],
            eval_end=config["eval_end"],
        )
        theta = np.array([250, 1.5, 0.5, 0.05, 0.4, 0, 3.0])
        theta[0] *= 1 + i * 0.1
        q, _ = simulate(
            1,
            theta,
            data["forcing"],
            y0=config["y0"],
            settings=config["settings"],
        )
        cfs = q * 100_000_000 / (86400 * 0.028316846592 * 1000)
        destination.write_text(
            "".join(
                f"{gauge} {d.year} {d.month} {d.day} {q:.15g} A\n"
                for d, q in zip(dates, cfs)
            ),
            encoding="utf-8",
        )
    return config


def main():
    """Save a portable example session and perform three iterations."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output",
        type=Path,
        required=True,
        help="New directory for artificial data and results.",
    )
    args = parser.parse_args()
    config = configuration(args.output / "artificial_data")
    session = args.output / "session.json"
    session.write_text(json.dumps(config, indent=2), encoding="utf-8")
    report = execute(config, args.output / "run")
    print(
        "Complete:",
        len(report["history"]),
        "iterations,",
        len(report["basins"]),
        "artificial basins.",
    )


if __name__ == "__main__":
    main()
