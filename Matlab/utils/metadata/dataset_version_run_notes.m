function notes = dataset_version_run_notes(notes,C)
% Record installed release evidence without guessing from GUI labels.
    heading = "Dataset version";
    rule = "----------------------------------------";
    current = strjoin(string(notes),newline);
    pattern = "(?s)\s*" + regexptranslate('escape',heading) ...
        + "\r?\n={40}\r?\n.*?" + regexptranslate('escape',rule) + "\s*";
    current = strip(regexprep(current,pattern,""));
    root = "";
    if isfield(C,'dirD'), root = string(C.dirD); end
    marker = fullfile(root,'MERV_Jp_v2_1.installed');
    code = "";
    try, code = string(region_helpers('code',C)); catch, end
    [dataset,~] = dataset_overview(code);
    if isempty(dataset), dataset = char(code); end
    release = regexp(dataset,'(?:\s+v|\s+)(\d+(?:\.\d+)*)$','tokens', ...
        'once');
    if isempty(release)
        details = "Configured dataset: " + string(dataset) + newline ...
            + ("Release number: not specified in the supported " + ...
                "product metadata.");
    else
        details = "Configured dataset release: " + string(dataset);
    end
    details = details + newline ...
        + ("Installed release: not independently confirmed (no " + ...
            "installation marker).");
    if code=="CAMELS_AU" && ...
        strlength(root)>0 && ...
        isfile(fullfile(root,'CAMELS_AUS_v2.03.installed'))
        evidence = strip(string(fileread(fullfile(root, ...
            'CAMELS_AUS_v2.03.installed'))));
        if evidence=="CAMELS-AUS v2.03"
            details = "Configured dataset release: CAMELS-AUS v2.03" + ...
                newline ...
                + ("Installed release: CAMELS-AUS v2.03 " + ...
                    "(installation marker).");
        end
    end
    if code=="CAMELS_JP" && ...
        strlength(root)>0 && ...
        isfile(marker)
        evidence = strip(string(fileread(marker)));
        if startsWith(evidence,"MERV-Jp 2.1;")
            details = "Configured dataset release: MERV-Jp 2.1" + ...
                newline ...
                + ("Installed release: MERV-Jp 2.1 (installation " + ...
                    "marker).") + newline ...
                + "Source: https://zenodo.org/records/22037429" + ...
                    newline ...
                + "Archive MD5: 1577739012977b7d16890c60917f2d65";
        end
    end
    block = heading + newline + ...
        "========================================" ...
        + newline + details + newline + "Data directory: " + root + ...
            newline + rule;
    notes = block;
    if strlength(current)>0, notes = current + newline + newline + ...
        block; end
end
