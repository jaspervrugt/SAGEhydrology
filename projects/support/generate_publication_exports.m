function value = path_literal(path)
parts = split(string(path),filesep);
value = strjoin("'" + parts + "'",',');
value = char(value);
end

function text = comment_rows(rows)
labelWidth = 15;
valueWidth = 76-(2+labelWidth+2);
text = '';
for k = 1:size(rows,1)
    lines = wrap_text(rows{k,2},valueWidth);
    for j = 1:numel(lines)
        label = '';
        separator = '  ';
        if j == 1
            label = rows{k,1};
            separator = ': ';
        end
        text = [text sprintf('%% %-*s%s%s\n',labelWidth,label, ...
            separator,lines{j})]; %#ok<AGROW>
    end
end
end

function lines = wrap_text(value,width)
words = regexp(strtrim(char(string(value))),'\s+','split');
lines = {};
current = '';
for k = 1:numel(words)
    candidate = strtrim([current ' ' words{k}]);
    if isempty(current) || numel(candidate) <= width
        current = candidate;
    else
        lines{end+1} = current; %#ok<AGROW>
        current = words{k};
    end
end
lines{end+1} = current;
end

function value = escape(value)
value = strrep(char(string(value)),'''','''''');
end
