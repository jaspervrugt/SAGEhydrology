function generate_publication_exports()
%GENERATE_PUBLICATION_EXPORTS Build the runnable Project 3--5 sources.
% These scripts deliberately use the same training pipeline as the GUI
% exporter, while basin selection is repeated from the publication split
% file so the sources do not embed thousands of prepared-basin values.

repo = fileparts(fileparts(fileparts(mfilename('fullpath'))));
template = fileread(fullfile(repo,'examples','run_SAGE_export_hymod.m'));
marker = '%% Initialize SAGEhydrology';
start = strfind(template,marker);
assert(~isempty(start),'The canonical SAGE export template is unavailable.');
tail = template(start(1):end);
old = ['% Select and order attributes for prepared basins ' newline ...
    'A = select_basin_attributes(A_reg,ID,bas.id_gauge);' newline ...
    '% Get spatial coordinates of basins ' newline ...
    'latlon = get_latlon(dirD,bas);'];
new = ['% Select publication basins and reproduce their stored split ' newline ...
    '[A,bas,latlon] = sample_basins(A_reg,ID,bas,prd, ...' newline ...
    '    gname,zone,dirD,file_univ,file_split);'];
tail = strrep(tail,old,new);

spec = project_specs(repo);
for k = 1:numel(spec)
    body = [header_text(spec(k)) configuration_text(spec(k)) tail];
    body = strrep(body,'write_header(mdl) ', ...
        header_call(spec(k)));
    body = strrep(body, ...
        ['mdl.crr_backend = misc.crr_backend; ' ...
        '% Keep training and postprocessing synchronized'], ...
        ['mdl.crr_backend = misc.crr_backend; ' ...
        '% Keep training and' newline ...
        '    % postprocessing synchronized']);
    body = strrep(body, ...
        ['C.runtime = struct(''lastIter'',i,''timing'',struct(''data'',' ...
        'prf.wallT_data,''initialization'',prf.wallT_init,''training'',' ...
        'prf.wallT_train,''information'',prf.wallT_info,''postprocessing'',' ...
        'prf.wallT_post,''gui'',prf.wallT_gui,''total'',prf.wallT_total));'], ...
        ['C.runtime = struct(''lastIter'',i,''timing'',struct( ...' newline ...
        '    ''data'',prf.wallT_data, ...' newline ...
        '    ''initialization'',prf.wallT_init, ...' newline ...
        '    ''training'',prf.wallT_train, ...' newline ...
        '    ''information'',prf.wallT_info, ...' newline ...
        '    ''postprocessing'',prf.wallT_post, ...' newline ...
        '    ''gui'',prf.wallT_gui,''total'',prf.wallT_total));']);
    fid = fopen(spec(k).output,'w','n','UTF-8');
    assert(fid >= 0,'Cannot write project source: %s',spec(k).output);
    cleaner = onCleanup(@() fclose(fid));
    fwrite(fid,body,'char');
    clear cleaner
end
end

