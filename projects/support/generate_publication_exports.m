function text = header_text(s)
periodStart = min(local_date(s.trainStart),local_date(s.evalStart));
periodEnd = max(local_date(s.trainEnd),local_date(s.evalEnd));
exported = char(datetime('now','Format','dd-MMM-yyyy HH:mm:ss'));
detailRows = { ...
    'Model',s.modelName; ...
    'Region',s.regionName; ...
    'Resolution',s.resolution; ...
    'Basins',sprintf('%d (training: %d; evaluation: %d)', ...
        s.K,s.Kt,s.Ke); ...
    'Period',sprintf('%s - %s',local_date_text(periodStart), ...
        local_date_text(periodEnd)); ...
    'Temporal split','Manual dates'; ...
    'Training',sprintf('%s - %s',local_date_text(local_date(s.trainStart)), ...
        local_date_text(local_date(s.trainEnd))); ...
    'Evaluation',sprintf('%s - %s',local_date_text(local_date(s.evalStart)), ...
        local_date_text(local_date(s.evalEnd))); ...
    'Loss function',s.lossName; ...
    'Data type',s.dataType; ...
    'Optimizer',s.optimizerName; ...
    'Exported',exported};
text = sprintf([ ...
    '%% ========================================================================\n' ...
    '%%   S A G E\n' ...
    '%%   Sensitivity-Aware Learning for Rapid Training of Process-Based\n' ...
    '%%   Hydrologic Models across Large Basin Samples\n' ...
    '%% ========================================================================\n' ...
    '%%\n%s%%\n%s%%\n' ...
    '%% Generated from the canonical SAGE GUI run-export pipeline.\n\n' ...
    'clear\nclc\n\nwallTimerTotal = tic; wallTData = 0;\n'], ...
    comment_rows({s.project,s.name;'Title',s.title;'Summary',s.summary}), ...
    comment_rows(detailRows));
end

function value = local_date(v)
value = datetime(v(3),v(2),v(1));
end

function value = local_date_text(v)
value = char(string(v,'dd MMM yyyy'));
end

